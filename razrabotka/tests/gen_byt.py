# python3 gen_byt.py out.xlsx [строк]
import sys, random, datetime, openpyxl
out = sys.argv[1]; n = int(sys.argv[2]) if len(sys.argv) > 2 else 1000
H = ['НОМЕР','ФИО','NNP','EXP_4','УЛИЦА','ДОМ','КОР','КВ','ТЕЛ','КОД_ЛГ','GIL','LGI','СК','ТАРИФ','КНИГА','ТИП_СЧ','РАЗР','N_СЧЕТЧИКА','KVP','ГОД',
     'НАЧ_ПОК','ДАТА_ПР','ПОК','ОПЛ_ПОК','ДАТА_ЗАМ','ПОК_СН_СЧ','N_ЗАМ_СЧ','ТИП_ЗАМ_СЧ','IDSS','N_F','ПР_ДИФ','ПР_ВОДА_ГА','КОМ_КВ','СОБСТВ','АСКУЭ',
     'МЕСТО_ПУ','ГОД_ЗАМ_ПУ','КВАР_ЗАМ_П','М_ТЕЛ','СОГЛ_СМС','СЕЛЬСОВЕТ','U','ЭЛ_ПУ','МП_ИНТ','ДАТА_НЗ','РАБОТА','ДАТА_ИЗВ','ВИД_ИЗВ','ДАТА_ДОГ',
     'Д_ПЕРЕОФ','КАТ_ГР','ПР_ПЛ']
random.seed(7)
fam = ['Тестов','Примеров','Образцов','Выдумкин','Пробный','Условный','Макетов','Шаблонов']
im = ['Иван','Пётр','Анна','Мария','Олег','Нина']
ot = ['Иванович','Петрович','Сергеевна','Олегович','Андреевна']
places = [('Тестовка','Пробный'), ('Образцово','Пробный'), ('Новая Выдумка','Условный'), ('Макетино','Условный')]
streets = ['Лесная ул.','Садовая ул.','Полевая ул.','Тихий пер.','Центральная ул.']
wb = openpyxl.Workbook(); ws = wb.active; ws.title = 'TEMP'; ws.append(H)
for i in range(n):
    np_, ss = places[i % len(places)]
    book = 1000 + i // 500
    nab = int('0%04d%03d%d' % (book % 10000, i % 1000, i % 10))   # число - ведущий 0 теряется, как в Excel
    row = [nab, '%s %s %s' % (fam[i % 8], im[i % 6], ot[i % 5]), np_, 3874, streets[(i // 7) % 5], (i // 3) % 60 + 1, '', (i % 3) or '',
           2000000 + i, 0, 1, 0, 0, 23, book, random.choice(['СЕ-208BY', 'СЕ-318BY', 'СО-505']), 6, 50000000 + i, 2, 2010 + i % 15,
           1, datetime.datetime(2025, 1 + i % 12, 1 + i % 28), 9000 + i % 900, 8000 + i % 800, None, 0, None, 'СЧ ОТКЛ ИНД.А' if i % 50 == 0 else None,
           6, None, None, None, 0, None, 1, 'Квартира подъезд', 0, 8, '+37529%07d' % i, 1, ss, 380 if i % 4 else 220, 1, 8, None, None,
           None, None, None, None, None, 2025]
    ws.append(row)
# 26.11: улица с именем - в быту полностью («Михаила Миля»), в юр базе - «М.Миля», «М Миля» (gen_ftu.py); частные дома 5 и 7
for j, dom in enumerate([5, 5, 7]):
    ws.append([int('099%04d' % j), 'Милевский Тест Тестович', 'Макетино', 3874, 'Михаила Миля ул.', dom, '', ''] + [None] * (len(H) - 8))
for c in ws['V'][1:]: c.number_format = 'dd.mm.yyyy'
wb.save(out)
print(out, n)
